import {chromium} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/');
await page.locator('.project-card').first().waitFor();
await page.waitForTimeout(4000);
await page.screenshot({path:'test-results/desktop-explore.png'});
await page.locator('.project-card').first().click();
await page.getByRole('button',{name:'เริ่มวิเคราะห์พื้นที่'}).click();
await page.locator('.results').waitFor({timeout:180000});
await page.getByLabel('ชั้นข้อมูล',{exact:true}).waitFor({timeout:120000});
await page.waitForFunction(()=>Array.from(document.querySelectorAll('.leaflet-overlay-pane img')).some(i=>i.src.includes('earthengine.googleapis.com')&&i.complete&&i.naturalWidth>0),{},{timeout:120000});
await page.getByLabel('ชั้นข้อมูล',{exact:true}).selectOption('evidence');
await page.waitForTimeout(5000);
await page.screenshot({path:'test-results/desktop-evidence.png'});
await page.getByLabel('เปรียบเทียบภาพก่อน / หลัง').check();
await page.getByLabel('เลื่อนเปรียบเทียบภาพ').fill('50');
await page.waitForFunction(()=>{const images=Array.from(document.querySelectorAll('.leaflet-overlay-pane img'));return images.length>0&&images.every(i=>i.complete&&i.naturalWidth>0);},{},{timeout:120000});
const clipping=await page.locator('.leaflet-overlay-pane .leaflet-layer').evaluateAll(es=>es.some(e=>e.style.clip.startsWith('rect(')));
if(!clipping)throw new Error('Before/after clipping was not applied');
await page.screenshot({path:'test-results/desktop-before-after.png'});
const viewport=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth}));
fs.writeFileSync('test-results/live-ui-validation.json',JSON.stringify({errors,viewport,results:await page.locator('.results').innerText()},null,2));
console.log('Live results, evidence layer, before/after slider:',errors.length?'FAIL':'PASS');
if(errors.length)throw new Error(errors.join('\n'));
await browser.close();
